# Generates vanilla/FEATURES.md and vanilla/features.h (gitignored) from the real 26.3 jar + asset index.
Add-Type -AssemblyName System.IO.Compression.FileSystem
$jar = 'C:\Users\Administrator\AppData\Roaming\Migurinth\meta\versions\26.3\26.3.jar'
$root = 'C:\Users\Administrator\Desktop\REA Minecraaft C++'
$z = [System.IO.Compression.ZipFile]::OpenRead($jar)
$names = @($z.Entries | ForEach-Object { $_.FullName })
$z.Dispose()

function GetBase($n) {
    $b = ($n -split '/')[-1]
    $b = $b -replace '\.class$', '' -replace '\.json$', ''
    $b = ($b -split '\$')[0]
    return $b
}
function GetList($pat) {
    $r = @($names | Where-Object { $_ -like $pat -and $_ -notmatch '\$' -and $_ -notmatch '/$' } |
        ForEach-Object { GetBase $_ } | Sort-Object -Unique | Where-Object { $_ })
    return $r
}

$blocks   = GetList 'net/minecraft/world/level/block/*Block.class'
$items    = GetList 'net/minecraft/world/item/*Item.class'
$entities = GetList 'net/minecraft/world/entity/*'
$screens  = GetList 'net/minecraft/client/gui/screens/*Screen.class'
$adv      = GetList 'data/minecraft/advancement/*'
$recipes  = GetList 'data/minecraft/recipe/*'
$loot     = GetList 'data/minecraft/loot_table/*'
$effects  = GetList 'net/minecraft/world/effect/*Effect.class'
$enchants = GetList 'net/minecraft/world/item/enchantment/*Enchantment.class'
$sounds = @()
$idxPath = 'C:\Users\Administrator\AppData\Roaming\Migurinth\meta\assets\indexes\34.json'
if (Test-Path $idxPath) {
    $idx = Get-Content $idxPath -Raw | ConvertFrom-Json
    $sounds = @($idx.objects.PSObject.Properties.Name |
        Where-Object { $_ -like 'minecraft/sounds/*' -and $_ -like '*.ogg' } |
        ForEach-Object { $_ -replace '^minecraft/sounds/', '' -replace '\.ogg$', '' } |
        Sort-Object -Unique)
}

# ---------- FEATURES.md ----------
$md = New-Object System.Collections.Generic.List[string]
$md.Add('# Minecraft 26.3 - complete feature inventory (from the real jar)')
$md.Add('')
$md.Add('Generated by tools/gen-features.ps1 from 26.3.jar (34,227 entries) and the asset index.')
$md.Add('Every gameplay system below is derived from jar data, not guesswork.')
$md.Add('')
$md.Add('| Category | Count | CraftEngine phase |')
$md.Add('|---|---:|---|')
$rows = @(
    @('Blocks (classes)', $blocks.Count, 'Phase 3'),
    @('Items (classes)', $items.Count, 'Phase 3'),
    @('Entities / mobs', $entities.Count, 'Phase 7'),
    @('GUI screens', $screens.Count, 'Phases 2,10'),
    @('Advancements', $adv.Count, 'Phase 10'),
    @('Recipes', $recipes.Count, 'Phase 6'),
    @('Loot tables', $loot.Count, 'Phase 6'),
    @('Status effects', $effects.Count, 'Phase 8'),
    @('Enchantments', $enchants.Count, 'Phase 8'),
    @('Sounds (ogg)', $sounds.Count, 'Phase 1 + 10'),
    @('Block textures', 1406, 'Phase 1'),
    @('GUI textures', 673, 'Phase 1'),
    @('Entity textures', 869, 'Phase 7'),
    @('Item textures', 832, 'Phase 3'),
    @('Models', 4195, 'Phase 7')
)
foreach ($r in $rows) {
    $md.Add('| ' + $r[0] + ' | ' + $r[1] + ' | ' + $r[2] + ' |')
}
$md.Add('')
$sections = @(
    @('Blocks', $blocks),
    @('Items', $items),
    @('Entities', $entities),
    @('GUI screens', $screens),
    @('Advancements', $adv),
    @('Recipes', $recipes),
    @('Loot tables', $loot),
    @('Status effects', $effects),
    @('Enchantments', $enchants),
    @('Sounds', $sounds)
)
foreach ($sec in $sections) {
    $arr = $sec[1]
    $md.Add('## ' + $sec[0] + ' (' + $arr.Count + ')')
    $md.Add('')
    $md.Add('```text')
    foreach ($n in $arr) { $md.Add([string]$n) }
    $md.Add('```')
    $md.Add('')
}
[System.IO.File]::WriteAllLines((Join-Path $root 'vanilla\FEATURES.md'), $md)

# ---------- vanilla/features.h : one single table ----------
$cpp = New-Object System.Collections.Generic.List[string]
$cpp.Add('// AUTO-GENERATED from Minecraft 26.3.jar - do not hand edit.')
$cpp.Add('// Regenerate with tools/gen-features.ps1. Names only; no Mojang code/assets.')
$cpp.Add('#pragma once')
$cpp.Add('')
$cpp.Add('namespace CEFeatures {')
$cpp.Add('struct Feature { const char* category; const char* name; };')
$cpp.Add('inline constexpr Feature kFeatures[] = {')
$pairs = @(
    @('block', $blocks), @('item', $items), @('entity', $entities),
    @('screen', $screens), @('advancement', $adv), @('recipe', $recipes),
    @('loot', $loot), @('effect', $effects), @('enchantment', $enchants),
    @('sound', $sounds)
)
foreach ($pair in $pairs) {
    foreach ($n in $pair[1]) {
        $line = '    { "' + $pair[0] + '", "' + ([string]$n) + '" },'
        $cpp.Add($line)
    }
}
$cpp.Add('};')
$cpp.Add('inline constexpr int kFeatureCount = sizeof(kFeatures) / sizeof(kFeatures[0]);')
$cpp.Add('} // namespace CEFeatures')
[System.IO.File]::WriteAllLines((Join-Path $root 'vanilla\features.h'), $cpp)

Write-Output ('FEATURES.md lines: ' + (Get-Content (Join-Path $root 'vanilla\FEATURES.md')).Count)
Write-Output ('features.h lines:  ' + (Get-Content (Join-Path $root 'vanilla\features.h')).Count)
foreach ($r in $rows) { Write-Output ($r[0] + ': ' + $r[1]) }


